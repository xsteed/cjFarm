-- 35 号:会员功能总闸(tb_config.member_enabled)。
--
-- 背景:会员入口的显隐不再由「小程序 AppSecret 是否已配置」推导,改为管理端
-- 「营业设置 → 会员功能」的独立开关(闸口见 application/service.memberSwitchOn)。
-- 公开配置(/api/customer/config)下发的 member_enabled 直接取本键,前端据此
-- 显隐小程序「我的」入口;登录与静默重登在 CustomerLoginByProvider 入口同受它约束。
--
-- 口径:
--   '1' 开放 —— 小程序底部「我的」入口与会员注册/登录照常;
--   '0'(默认)关闭 —— 顾客端整体隐藏会员入口,登录/静默重登一律拒绝。
-- 「默认关」语义(fail-closed):只有明确 '1' 才算开启(与读侧 SettingFlag 一致),
-- 未配 AppSecret 的部署升级后不会出现「入口在、点注册必失败」的哑火状态;
-- 需要会员的商家在管理端「营业设置 → 会员功能」手动打开。
--
-- 适用范围:仅用于存量库升级;新库请直接执行 migrations/full/{mysql,sqlite}/seed.sql
-- (已含该键)。后端启动时 store.EnsureSettingDefaults 也会补写同一默认值。
--
-- 幂等性:INSERT OR IGNORE 以 cfg_key 为主键判重,重复执行零变更;
--         管理员已把现值改为 '0' 的库不受影响(不覆盖已有值)。
INSERT OR IGNORE INTO tb_config(cfg_key, cfg_value) VALUES('member_enabled', '0');
