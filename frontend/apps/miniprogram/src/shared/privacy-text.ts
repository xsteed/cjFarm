// ============================================================================
// 《用户服务协议》《隐私政策》正文的唯一来源
//
// 为什么收在这里：隐私授权页只展示「采集了什么」，协议页展示完整条款，
// 两边说的是同一件事。分开放必然漂移（一边改了手机号用途、另一边还是旧文案），
// 而这类文案不一致正是被监管/平台指出合规问题时最难解释的一种。
//
// ⚠️ 上线前必改（法务 / 门店主体层面，不是技术问题）：
//   1) 全文的「本店」必须替换为**营业执照上的主体名称**，否则条款的签署方不明确；
//   2) 「联系方式」一节要填真实有效的门店电话或客服渠道 ——
//      留空会让「你可以联系我们行使权利」变成一句空话，本身就不符合《个人信息保护法》
//      关于「提供便捷行使权利方式」的要求；
//   3) 储值余额一节要与门店实际的储值规则（可否退、有无有效期）一致。
//      当前文案写的是「余额不设有效期、可申请退还剩余金额」，
//      与 pages/wallet 的界面文案同源；若门店另有约定，请同步改这里。
// ============================================================================

